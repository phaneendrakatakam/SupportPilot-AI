def test_general_response_without_tool_is_persisted(
    monkeypatch,
) -> None:
    install_fake_client(
        monkeypatch,
        [
            make_final_response(
                (
                    "That request is outside "
                    "SupportPilot's CloudDesk "
                    "support scope."
                )
            )
        ],
    )

    result = orchestrator.run_agent(
        message=(
            "Who will win the next "
            "cricket World Cup?"
        ),
        customer_id=None,
    )

    conversation_id = (
        result["conversation_id"]
    )

    try:
        assert (
            result["intent"]
            == "general"
        )

        assert (
            len(
                result["trace"]
            )
            == 2
        )

        assert (
            result["trace"][0]["type"]
            == "request"
        )

        assert (
            result["trace"][1]["type"]
            == "final_response"
        )

        with SessionLocal() as db:
            agent_run = db.get(
                AgentRun,
                result["run_id"],
            )

            assert (
                agent_run
                is not None
            )

            assert (
                agent_run.intent
                == "general"
            )

            assert (
                agent_run.prompt_version
                == "v1-agent-foundation-3"
            )

            executions = list(
                db.scalars(
                    select(
                        ToolExecution
                    ).where(
                        ToolExecution.run_id
                        == result["run_id"]
                    )
                ).all()
            )

            assert (
                executions
                == []
            )

            messages = list(
                db.scalars(
                    select(
                        Message
                    )
                    .where(
                        Message.conversation_id
                        == conversation_id
                    )
                    .order_by(
                        Message.created_at
                    )
                ).all()
            )

            assert [
                message.role
                for message in messages
            ] == [
                "user",
                "assistant",
            ]

    finally:
        cleanup_conversation(
            conversation_id
        )


