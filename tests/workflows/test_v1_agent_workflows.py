def test_unsupported_knowledge_fact_uses_safe_response(
    monkeypatch,
) -> None:
    """
    Exercise the knowledge-tool workflow without
    making a real Gemini embedding request.

    The retrieved passage is semantically related
    to subscriptions but does NOT establish
    whether lifetime plans exist.
    """

    safe_response = (
        "The available CloudDesk documentation "
        "does not provide enough information "
        "to confirm whether CloudDesk offers "
        "a lifetime subscription plan."
    )

    install_fake_client(
        monkeypatch,
        [
            make_tool_call_response(
                "search_knowledge_base",
                {
                    "query": (
                        "CloudDesk lifetime "
                        "subscription plan"
                    ),
                    "top_k": 3,
                },
            ),
            make_final_response(
                safe_response
            ),
        ],
    )

    def fake_knowledge_search(
        _db,
        _payload,
    ) -> KnowledgeSearchResult:
        return KnowledgeSearchResult(
            status="SUCCESS",
            results=[
                KnowledgePassage(
                    content=(
                        "CloudDesk subscription "
                        "charges are generally "
                        "non-refundable after a "
                        "billing cycle begins."
                    ),
                    source=(
                        "refund_policy.md"
                    ),
                    score=0.7414,
                )
            ],
            retrieval_mode=(
                "semantic-pgvector-"
                "gemini-embedding-2"
            ),
            error=None,
        )

    monkeypatch.setattr(
        orchestrator,
        "search_knowledge_base",
        fake_knowledge_search,
    )

    result = orchestrator.run_agent(
        message=(
            "Does CloudDesk provide a "
            "lifetime subscription plan?"
        ),
        customer_id=None,
    )

    conversation_id = (
        result["conversation_id"]
    )

    try:
        assert (
            result["intent"]
            == "knowledge"
        )

        assert (
            result["response"]
            == safe_response
        )

        assert (
            "does not offer"
            not in result[
                "response"
            ].lower()
        )

        tool_events = [
            event
            for event
            in result["trace"]
            if event["type"]
            == "tool_call"
        ]

        assert (
            len(tool_events)
            == 1
        )

        assert (
            tool_events[0]["tool"]
            == "search_knowledge_base"
        )

        assert (
            tool_events[0][
                "result_status"
            ]
            == "SUCCESS"
        )

        assert (
            tool_events[0][
                "result"
            ]["results"][0][
                "source"
            ]
            == "refund_policy.md"
        )

        with SessionLocal() as db:
            execution = db.scalar(
                select(
                    ToolExecution
                ).where(
                    ToolExecution.run_id
                    == result["run_id"]
                )
            )

            assert (
                execution
                is not None
            )

            assert (
                execution.tool_name
                == "search_knowledge_base"
            )

            assert (
                execution.result_status
                == "SUCCESS"
            )

    finally:
        cleanup_conversation(
            conversation_id
        )