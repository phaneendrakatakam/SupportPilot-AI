class FakeModels:
    """
    Minimal replacement for client.models.

    Each call to generate_content returns the
    next predefined fake Gemini response.
    """

    def __init__(
        self,
        responses: list[Any],
    ) -> None:
        self._responses = iter(
            responses
        )

    def generate_content(
        self,
        **_kwargs: Any,
    ) -> Any:
        response = next(
            self._responses
        )

        if isinstance(
            response,
            Exception,
        ):
            raise response

        return response


class FakeGeminiClient:
    """
    Minimal replacement for google.genai.Client.
    """

    def __init__(
        self,
        responses: list[Any],
    ) -> None:
        self.models = FakeModels(
            responses
        )


def make_tool_call_response(
    tool_name: str,
    arguments: dict[str, Any],
) -> Any:
    """
    Simulate Gemini requesting a tool.
    """

    function_call = SimpleNamespace(
        name=tool_name,
        args=arguments,
    )

    model_content = types.Content(
        role="model",
        parts=[
            types.Part.from_text(
                text=(
                    f"Calling {tool_name}"
                )
            )
        ],
    )

    return SimpleNamespace(
        function_calls=[
            function_call
        ],
        candidates=[
            SimpleNamespace(
                content=model_content
            )
        ],
        text=None,
    )


def make_final_response(
    text: str,
) -> Any:
    """
    Simulate Gemini returning its final
    customer-facing answer.
    """

    return SimpleNamespace(
        function_calls=[],
        candidates=[],
        text=text,
    )


def install_fake_client(
    monkeypatch,
    responses: list[Any],
) -> None:
    """
    Replace the live Gemini client so workflow
    tests consume zero external API quota.
    """

    fake_client = FakeGeminiClient(
        responses
    )

    monkeypatch.setattr(
        orchestrator.settings,
        "gemini_api_key",
        "test-api-key",
    )

    monkeypatch.setattr(
        orchestrator.genai,
        "Client",
        lambda **_kwargs: fake_client,
    )


def cleanup_conversation(
    conversation_id: str,
) -> None:
    """
    Remove database records generated by one
    workflow test.

    This keeps the local development database
    clean after pytest completes.
    """

    with SessionLocal() as db:
        run_ids = list(
            db.scalars(
                select(
                    AgentRun.run_id
                ).where(
                    AgentRun.conversation_id
                    == conversation_id
                )
            ).all()
        )

        if run_ids:
            db.execute(
                delete(
                    ToolExecution
                ).where(
                    ToolExecution.run_id.in_(
                        run_ids
                    )
                )
            )

        db.execute(
            delete(
                Message
            ).where(
                Message.conversation_id
                == conversation_id
            )
        )

        db.execute(
            delete(
                AgentRun
            ).where(
                AgentRun.conversation_id
                == conversation_id
            )
        )

        db.execute(
            delete(
                Conversation
            ).where(
                Conversation.conversation_id
                == conversation_id
            )
        )

        db.commit()


